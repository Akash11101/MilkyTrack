// Copies Poppins + Mukta (Latin + Devanagari) from @fontsource into www/fonts
// so the app looks the same offline. Safe to fail: the app falls back to
// system fonts / Google Fonts when this has not run.
import fs from "node:fs";
import path from "node:path";

const out = "www/fonts";
fs.mkdirSync(out, { recursive: true });
const wanted = {
  poppins: ["500", "600", "700"],
  mukta: ["400", "500", "600", "700"],
};
let css = "/* generated by scripts/prepare-fonts.mjs */\n";
let files = 0;
for (const [pkg, weights] of Object.entries(wanted)) {
  const base = path.join("node_modules", "@fontsource", pkg);
  for (const w of weights) {
    const cssFile = path.join(base, `${w}.css`);
    if (!fs.existsSync(cssFile)) { console.warn("missing", cssFile); continue; }
    const blocks = fs.readFileSync(cssFile, "utf8").match(/@font-face\s*{[^}]*}/g) || [];
    for (let b of blocks) {
      const range = (b.match(/unicode-range:\s*([^;]+);/) || [])[1] || "";
      const wantSubset = /U\+0900|U\+0000-00FF/.test(range) || !range; // devanagari + latin
      if (!wantSubset) continue;
      const m = b.match(/url\(\.\/files\/([^)]+?\.woff2)\)/);
      if (!m) continue;
      const src = path.join(base, "files", m[1]);
      if (!fs.existsSync(src)) continue;
      fs.copyFileSync(src, path.join(out, m[1]));
      b = b.replace(/src:[^;]+;/, `src: url(./${m[1]}) format("woff2");`);
      css += b + "\n";
      files++;
    }
  }
}
fs.writeFileSync(path.join(out, "fonts.css"), css);
console.log(`fonts: ${files} font faces written to ${out}`);
